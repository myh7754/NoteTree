/**
 * 노트에서 입력하는 순간 기호로 바꿔 주는 글자 조합.
 *
 * 공부 노트에는 "A → B", "a ≠ b" 같은 표기가 많은데 키보드로는 바로 칠 수 없다.
 * 코드 블록과 `짧은 코드` 안에서는 바뀌지 않는다(편집기의 입력 규칙이 코드를 건너뛴다) —
 * 거기서는 `->`와 `!=`가 진짜 코드다.
 */
export const SYMBOL_RULES: [find: RegExp, replace: string][] = [
  [/←>$/, '↔'], // <-> : 앞의 <- 가 먼저 ←로 바뀌므로 그 뒤에 > 가 오는 꼴로 잡는다
  [/->$/, '→'],
  [/<-$/, '←'],
  [/=>$/, '⇒'],
  [/!=$/, '≠'],
  [/<=$/, '≤'],
  [/>=$/, '≥'],
];
